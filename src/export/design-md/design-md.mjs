// Helpers for the export-design-md skill. No dependencies beyond Node.
//
//   uxagent export design-md collect
//     Prints one Markdown bundle of everything the export draws on: the filled-in parts of
//     the guidelines folder (stub placeholders, comments, and project-specific sections
//     stripped) and a flat digest of every token under the Figma unpacked tokens and the
//     supplemental folder. Exit 3 when there is nothing to export yet.
//
//   uxagent export design-md lint [file]
//     Runs Google's DESIGN.md linter (pinned below) on the configured DESIGN.md or [file],
//     then uxagent's own checks. Exit non-zero on any error.

import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";
import { cleanGuideline, guidelineFiles, guidelinesDir, repoDirs, tokenGroups } from "./read-docs.mjs";

const LINTER = "@google/design.md@0.4.0";
export const MARKER = "GENERATED by /export-design-md";

const rel = (config, p) => relative(config.root, p).split(sep).join("/");

export function collect(config) {
  const sha = (() => {
    try { return execFileSync("git", ["-C", config.root, "rev-parse", "--short", "HEAD"], { stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); }
    catch { return "unknown"; }
  })();
  const date = new Date().toISOString().slice(0, 10);
  const parts = [
    "# DESIGN.md export bundle",
    "",
    `Write to: \`${config.paths.designMd}\``,
    `Marker line (put right after the front matter): \`<!-- ${MARKER} from ${config.paths.designSystem}/ @ ${sha} on ${date}. Do not edit by hand; edit the sources and re-export. -->\``,
  ];

  const filled = [];
  const empty = [];
  const guidelineParts = [];
  for (const f of guidelineFiles(config)) {
    const content = cleanGuideline(readFileSync(join(guidelinesDir(config), f), "utf8"));
    if (content) {
      filled.push(f);
      guidelineParts.push(`## Guideline: ${f}\n\n${content}`);
    } else {
      empty.push(f);
    }
  }
  const groups = tokenGroups(config);
  const tokenCount = groups.reduce((n, g) => n + g.tokens.length, 0);

  parts.push(
    "",
    `Filled guidelines: ${filled.join(", ") || "none"}`,
    `Unfilled (omit their sections): ${empty.join(", ") || "none"}`,
    `Tokens: ${tokenCount} in ${groups.length} file(s)`,
    "",
    ...guidelineParts.flatMap((p) => [p, ""]),
  );
  for (const { file, tokens } of groups) {
    parts.push(`## Tokens: ${rel(config, file)}`, "", "| Path | Type | Value |", "| --- | --- | --- |");
    for (const t of tokens) parts.push(`| ${t.path} | ${t.type} | ${t.value.replace(/\|/g, "\\|")} |`);
    parts.push("");
  }
  console.log(parts.join("\n"));

  if (!filled.length && !tokenCount) {
    console.error("Nothing to export yet: every guideline is a stub and there are no tokens.");
    return 3;
  }
  return 0;
}

export function lint(config, file) {
  const path = file ? resolve(file) : config.abs(config.paths.designMd);
  if (!existsSync(path)) {
    console.error(`No file at ${rel(config, path)}. Run the export first.`);
    return 2;
  }
  const result = spawnSync("npx", ["--yes", LINTER, "lint", path], { stdio: "inherit" });
  if (result.error) {
    console.error(`Could not run ${LINTER}: ${result.error.message}`);
    return 2;
  }

  const text = readFileSync(path, "utf8");
  const problems = [];
  if (!text.includes(MARKER)) problems.push(`missing the "${MARKER}" marker comment`);
  if (/^##\s+Components\s*$/m.test(text)) problems.push("has a Components section; the portable export leaves components out");
  if (new RegExp(`\`(${repoDirs(config).join("|")})/`).test(text)) problems.push("mentions project paths; the portable export must stand alone");
  for (const p of problems) console.error(`repo check: ${p}`);

  return result.status || (problems.length ? 1 : 0);
}
