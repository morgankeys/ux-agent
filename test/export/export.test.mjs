import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { run, tempProject, write } from './helpers.mjs';

test('platforms --self-test passes', (t) => {
  const cwd = fs.mkdtempSync(path.join(os.tmpdir(), 'uxagent-cwd-'));
  t.after(() => fs.rmSync(cwd, { recursive: true, force: true }));
  const r = run(cwd, ['platforms', '--self-test']);
  assert.equal(r.code, 0, r.err);
  assert.match(r.out, /self-test ok/);
});

test('platforms --list names every target', (t) => {
  const cwd = fs.mkdtempSync(path.join(os.tmpdir(), 'uxagent-cwd-'));
  t.after(() => fs.rmSync(cwd, { recursive: true, force: true }));
  const r = run(cwd, ['platforms', '--list']);
  assert.equal(r.code, 0);
  for (const id of ['design-md', 'lovable', 'replit', 'bolt', 'v0', 'figma-make']) assert.match(r.out, new RegExp(`^${id}\\t`, 'm'));
});

test('platforms writes the packages under the configured exports folder', (t) => {
  const root = tempProject(t);
  const r = run(root, ['platforms']);
  assert.equal(r.code, 0, r.err);
  const dest = path.join(root, 'design-system/exports/platforms');
  for (const f of ['lovable/instructions.md', 'lovable/guidelines/setup.md', 'bolt/project-prompt.md', 'v0/import-notes.md', 'figma-make/tokens.css', 'replit/replit.md', 'design-md/README.md']) {
    assert.ok(fs.existsSync(path.join(dest, f)), `missing ${f}`);
  }
  const instructions = fs.readFileSync(path.join(dest, 'lovable/instructions.md'), 'utf8');
  assert.match(instructions, /chrome recedes/);
  assert.match(instructions, /GENERATED by uxagent .* from design-system\./);
  assert.doesNotMatch(instructions, /Docs\/|Export\//);
  assert.match(fs.readFileSync(path.join(dest, 'figma-make/tokens.css'), 'utf8'), /--color-primary: #112233;/);
  assert.match(fs.readFileSync(path.join(dest, 'design-md/README.md'), 'utf8'), /design-system\/exports\/DESIGN\.md/);
});

test('platforms [targets] limits output, and --out redirects it', (t) => {
  const root = tempProject(t);
  const r = run(root, ['platforms', 'v0', '--out', 'elsewhere']);
  assert.equal(r.code, 0, r.err);
  assert.ok(fs.existsSync(path.join(root, 'elsewhere/v0/import-notes.md')));
  assert.ok(!fs.existsSync(path.join(root, 'elsewhere/lovable')));
  assert.ok(!fs.existsSync(path.join(root, 'design-system/exports')));
  assert.equal(run(root, ['platforms', 'nope']).code, 1);
});

test('platforms packages a valid component port from platform-components', (t) => {
  const root = tempProject(t);
  write(root, 'design-system/platform-components/Button.tsx', 'export default function Button() { return <button className="btn" data-kind="primary">Go</button>; }\n');
  write(root, 'design-system/platform-components/manifest.json', JSON.stringify({ components: [{ name: 'Button', source: 'src/Button.vue', file: 'Button.tsx' }] }));
  const r = run(root, ['platforms', 'lovable']);
  assert.equal(r.code, 0, r.err);
  assert.match(r.out, /Components: Button/);
  assert.ok(fs.existsSync(path.join(root, 'design-system/exports/platforms/lovable/project/src/components/Button.tsx')));
});

