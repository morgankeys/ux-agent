test('design-md collect bundles guideline content and tokens', (t) => {
  const root = tempProject(t);
  const r = run(root, ['design-md', 'collect']);
  assert.equal(r.code, 0, r.err);
  assert.match(r.out, /chrome recedes/);
  assert.match(r.out, /Write to: `design-system\/exports\/DESIGN\.md`/);
  assert.match(r.out, /GENERATED by \/export-design-md from design-system\/ @ unknown on \d{4}-\d\d-\d\d/);
  assert.match(r.out, /Tokens: design-system\/figma\/tokens\/unpacked\/Color\/modes\.tokens\.json/);
});

test('design-md collect reads the project git state when there is one', (t) => {
  const root = tempProject(t);
  const git = (...a) => import('node:child_process').then(({ spawnSync }) => spawnSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@t', ...a], { cwd: root, encoding: 'utf8' }));
  return git('init', '-q').then(() => git('add', '.')).then(() => git('commit', '-q', '-m', 'x')).then((c) => {
    if (c.status !== 0) return; // git unavailable: skip
    const r = run(root, ['design-md', 'collect']);
    assert.match(r.out, /from design-system\/ @ [0-9a-f]{4,}/);
  });
});

test('design-md collect exits 3 when everything is a stub', (t) => {
  const root = tempProject(t);
  fs.rmSync(path.join(root, 'design-system/figma'), { recursive: true });
  write(root, 'design-system/guidelines/overview.md', '# Overview\n\n## Summary\n\n…\n');
  assert.equal(run(root, ['design-md', 'collect']).code, 3);
});

test('a non-default paths.designSystem is honoured', (t) => {
  const root = tempProject(t, { designSystem: 'docs/ds' });
  assert.ok(!fs.existsSync(path.join(root, 'design-system')));
  const collect = run(root, ['design-md', 'collect']);
  assert.equal(collect.code, 0, collect.err);
  assert.match(collect.out, /chrome recedes/);
  assert.match(collect.out, /Write to: `docs\/ds\/exports\/DESIGN\.md`/);
  assert.match(collect.out, /from docs\/ds\/ @/);
  const r = run(root, ['platforms', 'lovable']);
  assert.equal(r.code, 0, r.err);
  assert.ok(fs.existsSync(path.join(root, 'docs/ds/exports/platforms/lovable/instructions.md')));
  assert.ok(!fs.existsSync(path.join(root, 'design-system')));
  assert.match(fs.readFileSync(path.join(root, 'docs/ds/exports/platforms/lovable/instructions.md'), 'utf8'), /from docs\/ds\./);
});

